// Builds `src/features/skills/domain/aptitude/speciesFacts.generated.ts` from
// the Battle Catalog: the default form's types and base stats per species.
//
//   node scripts/skills/build-species-facts.mjs
//
// Skills needs these synchronously (client and a future server), and the
// catalog itself is a lazily loaded 300 KB chunk. This is a projection of it,
// regenerated, never hand-edited.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const core = JSON.parse(readFileSync(resolve(root, 'src/features/battle/catalog/generated/core.json'), 'utf8'))
const out = resolve(root, 'src/features/skills/domain/aptitude/speciesFacts.generated.ts')

const defaults = core.forms.filter(form => form.isDefault).sort((a, b) => a.speciesId - b.speciesId)
const rows = defaults.map(form => {
  const types = form.types.map(type => `'${type}'`).join(', ')
  return `  [${form.speciesId}, '${form.name}', [${types}], [${form.baseStats.join(', ')}]],`
})

writeFileSync(out, `// GENERATED by scripts/skills/build-species-facts.mjs — do not edit by hand.
// Source: Battle Catalog ${core.catalogVersion}, default form of each species.
// Row: [speciesId, canonical name, types, base stats (hp, atk, def, spa, spd, spe)].

import type { SpeciesFactsRow } from './speciesFacts'

export const SPECIES_FACTS_ROWS: readonly SpeciesFactsRow[] = [
${rows.join('\n')}
]
`)
console.log(`wrote ${rows.length} species to ${out}`)
