// Bundles the ECO-GAMEPLAY-2 test battle for the realtime service: the EXISTING battle authority,
// rules, catalog and Pokémon model (unchanged), wrapped by
// src/features/ecosystem/server/encounterBattleRuntime.ts with its synthetic sandbox fixtures.
// Same convention as bundle-encounters.mjs / bundle-admission.mjs: one generated, dependency-free
// ES module, never a hand copy. The catalog's dynamic JSON imports are inlined (no code splitting).
//
//   node scripts/integration/bundle-battle.mjs                     write the bundle
//   node scripts/integration/bundle-battle.mjs --check             exit 1 if missing or stale; writes nothing
//   node scripts/integration/bundle-battle.mjs --output <file>     use another file (tests)
//
// Reproducible: fixed working directory, repo-relative module comments, line endings normalised to
// \n. A vitest guard (src/features/ecosystem/server/battleBundle.test.ts) fails when it is stale.

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

export const ROOT = fileURLToPath(new URL('../../', import.meta.url))
export const ENTRY = 'src/features/ecosystem/server/encounterBattleRuntime.ts'
export const OUTPUT = fileURLToPath(new URL('../../services/realtime/src/world/ecosystem/encounterBattle.generated.js', import.meta.url))

const HEADER = `// GENERATED by scripts/integration/bundle-battle.mjs from
// src/features/ecosystem/server/encounterBattleRuntime.ts (+ src/features/battle/{authority,rules,catalog}/**,
// src/features/pokemon/model/** and the battle catalog JSON). Do not edit.
// Rebuild with: node scripts/integration/bundle-battle.mjs
`

/** Builds the bundle text. `plugins` exists for the drift tests only. */
export async function bundleBattle({ plugins = [] } = {}) {
  const result = await build({
    entryPoints: [ENTRY], absWorkingDir: ROOT, bundle: true, write: false, format: 'esm', platform: 'neutral',
    target: 'es2022', legalComments: 'none', logLevel: 'silent', treeShaking: true, splitting: false, plugins,
  })
  return HEADER + result.outputFiles[0].text.replace(/\r\n/g, '\n')
}

/** 'fresh' | 'stale' | 'missing' for the file at `output`, compared with `fresh`. Reads only. */
export async function bundleStatus(fresh, output = OUTPUT) {
  let current
  try {
    current = await readFile(output, 'utf8')
  } catch (error) {
    if (error?.code === 'ENOENT') return 'missing'
    throw error
  }
  return current.replace(/\r\n/g, '\n') === fresh ? 'fresh' : 'stale'
}

function outputFromArgs(argv) {
  const i = argv.indexOf('--output')
  if (i < 0) return OUTPUT
  if (!argv[i + 1]) throw new Error('--output needs a file path')
  return argv[i + 1]
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const output = outputFromArgs(process.argv)
  const fresh = await bundleBattle()
  if (process.argv.includes('--check')) {
    const status = await bundleStatus(fresh, output)
    if (status !== 'fresh') {
      console.error(`encounterBattle.generated.js is ${status}: run node scripts/integration/bundle-battle.mjs`)
      process.exit(1)
    }
    console.log('encounterBattle.generated.js is up to date')
  } else {
    await writeFile(output, fresh)
    console.log(`wrote ${output} (${fresh.length} bytes)`)
  }
}
