// Bundles the SKILLS service + the WORLD adapter for the realtime service
// (INTEGRATION-1). The realtime process is plain JavaScript with no build step
// (its Docker context is services/realtime), so the TypeScript rules reach it
// as one generated, dependency-free ES module — the option SKILLS' contract
// prefers over rewriting rules by hand.
//
//   node scripts/integration/bundle-skills.mjs          write the bundle
//   node scripts/integration/bundle-skills.mjs --check  exit 1 if it drifted
//
// A vitest guard (src/features/worldSkills/serverBundle.test.ts) runs the same
// build and fails when the committed file is stale.

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

export const ENTRY = fileURLToPath(new URL('../../src/features/worldSkills/server/skillsWorldPolicy.ts', import.meta.url))
export const OUTPUT = fileURLToPath(new URL('../../services/realtime/src/world/skills/skills.generated.js', import.meta.url))

const HEADER = `// GENERATED by scripts/integration/bundle-skills.mjs from
// src/features/worldSkills/server/skillsWorldPolicy.ts (+ src/features/skills/**).
// Do not edit. Rebuild with: node scripts/integration/bundle-skills.mjs
`

export async function bundleSkills() {
  const result = await build({
    entryPoints: [ENTRY], bundle: true, write: false, format: 'esm', platform: 'neutral', target: 'es2022',
    legalComments: 'none', logLevel: 'silent', treeShaking: true,
  })
  return HEADER + result.outputFiles[0].text.replace(/\r\n/g, '\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const fresh = await bundleSkills()
  if (process.argv.includes('--check')) {
    const current = (await readFile(OUTPUT, 'utf8').catch(() => '')).replace(/\r\n/g, '\n')
    if (current !== fresh) { console.error('skills.generated.js is stale: run node scripts/integration/bundle-skills.mjs'); process.exit(1) }
  } else {
    await writeFile(OUTPUT, fresh)
    console.log(`wrote ${OUTPUT} (${fresh.length} bytes)`)
  }
}
