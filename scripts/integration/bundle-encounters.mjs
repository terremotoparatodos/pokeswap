// Bundles the encounter catalog (ECO-1) and population engine (ECO-2A) for the
// realtime service (ECO-2B). Same convention as bundle-skills.mjs: the realtime
// process is plain JavaScript with no build step, so the TypeScript rules reach
// it as one generated, dependency-free ES module — never as a hand copy.
//
//   node scripts/integration/bundle-encounters.mjs                     write the bundle
//   node scripts/integration/bundle-encounters.mjs --check             exit 1 if missing or stale; writes nothing
//   node scripts/integration/bundle-encounters.mjs --output <file>     use another file (tests)
//
// Reproducible: esbuild runs with a fixed working directory (the repository
// root), so the only paths in the output are repo-relative module comments;
// no timestamps, no absolute paths, line endings normalised to \n.
//
// A vitest guard (src/features/ecosystem/server/encounterBundle.test.ts) runs
// the same build and fails when the committed file is stale.

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

export const ROOT = fileURLToPath(new URL('../../', import.meta.url))
export const ENTRY = 'src/features/ecosystem/server/encounterRuntime.ts'
export const OUTPUT = fileURLToPath(new URL('../../services/realtime/src/world/ecosystem/encounters.generated.js', import.meta.url))

const HEADER = `// GENERATED by scripts/integration/bundle-encounters.mjs from
// src/features/ecosystem/server/encounterRuntime.ts (+ src/features/ecosystem/{encounters,population}/**).
// Do not edit. Rebuild with: node scripts/integration/bundle-encounters.mjs
`

/**
 * Builds the bundle text. `plugins` exists for the drift tests only (they
 * rewrite one source in memory to prove a change is detected).
 */
export async function bundleEncounters({ plugins = [] } = {}) {
  const result = await build({
    entryPoints: [ENTRY], absWorkingDir: ROOT, bundle: true, write: false, format: 'esm', platform: 'neutral',
    target: 'es2022', legalComments: 'none', logLevel: 'silent', treeShaking: true, plugins,
  })
  return HEADER + result.outputFiles[0].text.replace(/\r\n/g, '\n')
}

/** 'fresh' | 'stale' | 'missing' for the file at `output`, compared with `fresh`. Reads only. */
export async function bundleStatus(fresh, output = OUTPUT) {
  let current
  try {
    current = await readFile(output, 'utf8')
  } catch (error) {
    if (error?.code === 'ENOENT') return 'missing'
    throw error
  }
  return current.replace(/\r\n/g, '\n') === fresh ? 'fresh' : 'stale'
}

function outputFromArgs(argv) {
  const i = argv.indexOf('--output')
  if (i < 0) return OUTPUT
  if (!argv[i + 1]) throw new Error('--output needs a file path')
  return argv[i + 1]
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const output = outputFromArgs(process.argv)
  const fresh = await bundleEncounters()
  if (process.argv.includes('--check')) {
    const status = await bundleStatus(fresh, output)
    if (status !== 'fresh') {
      console.error(`encounters.generated.js is ${status}: run node scripts/integration/bundle-encounters.mjs`)
      process.exit(1)
    }
    console.log('encounters.generated.js is up to date')
  } else {
    await writeFile(output, fresh)
    console.log(`wrote ${output} (${fresh.length} bytes)`)
  }
}
