// Bundles the ADMITTED encounter population (ECO-GAMEPLAY-1) for the realtime
// service: the R1/R2 gate with this build's verified geometry, nests, capacity
// and catalogs, and only intention-level operations on an admitted state.
// Same convention as bundle-encounters.mjs: one generated, dependency-free ES
// module, never a hand copy.
//
//   node scripts/integration/bundle-admission.mjs                     write the bundle
//   node scripts/integration/bundle-admission.mjs --check             exit 1 if missing or stale; writes nothing
//   node scripts/integration/bundle-admission.mjs --output <file>     use another file (tests)
//
// `geometryAdmission.ts` imports the verified snapshot with Vite's `?raw`. Plain
// Node cannot resolve that suffix, so the build inlines the file's TEXT as a
// string literal (the `eco-raw` plugin): the immutable build value the gate
// compares against, exactly as under Vite. Reproducible: fixed working
// directory, repo-relative module comments, line endings normalised to \n.
//
// A vitest guard (src/features/ecosystem/server/admissionBundle.test.ts) runs
// the same build and fails when the committed file is stale.

import { readFile, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

export const ROOT = fileURLToPath(new URL('../../', import.meta.url))
export const ENTRY = 'src/features/ecosystem/server/admissionRuntime.ts'
export const OUTPUT = fileURLToPath(new URL('../../services/realtime/src/world/ecosystem/admission.generated.js', import.meta.url))

const HEADER = `// GENERATED by scripts/integration/bundle-admission.mjs from
// src/features/ecosystem/server/admissionRuntime.ts (+ src/features/ecosystem/{encounters,population,map}/**
// and the species of src/features/battle/catalog/generated/core.json).
// Do not edit. Rebuild with: node scripts/integration/bundle-admission.mjs
`

/** Vite's `?raw`: the file's text as a string, resolved by a repo-relative path. */
const rawText = {
  name: 'eco-raw',
  setup(builder) {
    builder.onResolve({ filter: /\?raw$/ }, args => ({
      namespace: 'eco-raw',
      path: relative(ROOT, join(args.resolveDir, args.path.replace(/\?raw$/, ''))).replace(/\\/g, '/'),
    }))
    builder.onLoad({ filter: /.*/, namespace: 'eco-raw' }, async args => ({
      contents: (await readFile(join(ROOT, args.path), 'utf8')).replace(/\r\n/g, '\n'), loader: 'text',
    }))
  },
}

/** Builds the bundle text. `plugins` exists for the drift tests only. */
export async function bundleAdmission({ plugins = [] } = {}) {
  const result = await build({
    entryPoints: [ENTRY], absWorkingDir: ROOT, bundle: true, write: false, format: 'esm', platform: 'neutral',
    target: 'es2022', legalComments: 'none', logLevel: 'silent', treeShaking: true, plugins: [...plugins, rawText],
  })
  return HEADER + result.outputFiles[0].text.replace(/\r\n/g, '\n')
}

/** 'fresh' | 'stale' | 'missing' for the file at `output`, compared with `fresh`. Reads only. */
export async function bundleStatus(fresh, output = OUTPUT) {
  let current
  try {
    current = await readFile(output, 'utf8')
  } catch (error) {
    if (error?.code === 'ENOENT') return 'missing'
    throw error
  }
  return current.replace(/\r\n/g, '\n') === fresh ? 'fresh' : 'stale'
}

function outputFromArgs(argv) {
  const i = argv.indexOf('--output')
  if (i < 0) return OUTPUT
  if (!argv[i + 1]) throw new Error('--output needs a file path')
  return argv[i + 1]
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const output = outputFromArgs(process.argv)
  const fresh = await bundleAdmission()
  if (process.argv.includes('--check')) {
    const status = await bundleStatus(fresh, output)
    if (status !== 'fresh') {
      console.error(`admission.generated.js is ${status}: run node scripts/integration/bundle-admission.mjs`)
      process.exit(1)
    }
    console.log('admission.generated.js is up to date')
  } else {
    await writeFile(output, fresh)
    console.log(`wrote ${output} (${fresh.length} bytes)`)
  }
}
