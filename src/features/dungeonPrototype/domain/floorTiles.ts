// From a floor plan to WildLands underground (D1 §6, rebuilt in D1.2.1).
//
// D1.2.1 changed the reference. It used to be "a Pokémon cave": rooms joined by
// one-tile corridors. It is now **WildLands put inside a cave**, so the floor is
// generated the way a stretch of overworld reads — open ground with shape, wide
// natural routes, water with a shore, patches of biome — and the room graph that
// still drives the rules is deliberately invisible in the result.
//
// The plan layer above (floorPlan.ts) is untouched: same seed, same definition,
// same floor, same rooms, same links, same encounters. Only the *spatial output*
// changed.
//
// D1.2.2 sends the last floor somewhere else entirely: a boss floor is a
// designed room (bossRoom.ts), not a procedural one.
//
// Deterministic from the floor's own seed, so the map a player sees can be
// regenerated by a server that has the seed.

